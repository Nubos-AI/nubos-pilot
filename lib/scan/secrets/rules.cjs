const { NubosPilotError } = require('../../core.cjs');

const CI_WORD_RE = /^[A-Za-z0-9_]+$/;

function ci(word) {
  if (typeof word !== 'string' || !CI_WORD_RE.test(word)) {
    throw new NubosPilotError(
      'secrets-keyword-unsafe',
      'a case-insensitive keyword must match [A-Za-z0-9_]+',
      { word: String(word) },
    );
  }
  let out = '';
  for (const ch of word) {
    const lower = ch.toLowerCase();
    const upper = ch.toUpperCase();
    out += lower === upper ? ch : '[' + lower + upper + ']';
  }
  return out;
}

const GAP = '[_.\\-]?';
const SEP = '["\']?\\s*(?:[:=]|=>)\\s*["\']?';

function keyword(parts) {
  return parts.join(GAP);
}

function optional(source) {
  return '(?:' + source + GAP + ')?';
}

function anyOf(sources) {
  return '(?:' + sources.join('|') + ')';
}

function assigned(keySource, valueSource) {
  return keySource + SEP + valueSource;
}

