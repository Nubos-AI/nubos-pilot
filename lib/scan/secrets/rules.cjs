function _freeze(rules) {
  for (const rule of rules) {
    for (const key of ['cwe', 'paths', 'exclude_paths', 'substrings']) {
      if (Array.isArray(rule[key])) Object.freeze(rule[key]);
    }
    if (rule.entropy) Object.freeze(rule.entropy);
    Object.freeze(rule);
  }
  return Object.freeze(rules);
}

