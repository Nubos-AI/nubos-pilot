test('RGH-13: a dangling depends_on is warned about on stderr even on success', () => {
  const root = _project({
    roadmap: [
      'schema_version: 2',
      'milestones:',
      '  - id: M002',
      '    name: Audit log',
      '    status: pending',
      '    depends_on: M099',
      '    slices: []',
      '',
    ].join('\n'),
    tasks: [],
  });
  try {
    const c = _ctx(root);
    assert.equal(handler.run([], c.ctx), 0, 'a roadmap defect must not fail the render');
    // A diagram that silently omits an edge reads as complete, which is worse
    // than no diagram at all.
    assert.match(c.err(), /dangling dependency: M002 depends_on M099/);
  } finally {
    _cleanup(root);
  }
});

