test('RGH-15: there is no verb that writes roadmap.yaml', () => {
  const root = _project();
  const roadmap = path.join(root, '.nubos-pilot', 'roadmap.yaml');
  const before = fs.readFileSync(roadmap, 'utf-8');
  try {
    for (const args of [[], ['--format', 'dot'], ['--markdown'], ['--json'], ['--level', 'slice']]) {
      handler.run(args, _ctx(root).ctx);
    }
    assert.equal(fs.readFileSync(roadmap, 'utf-8'), before, 'the renderer must never mutate the plan');
  } finally {
    _cleanup(root);
  }
});

test('RGC-14: a conditional roadmap renders its gate, not a plain serial chain', () => {
  const root = _project({
    tasks: [],
    roadmap: [
      'schema_version: 3',
      'milestones:',
      '  - id: M001',
      '    number: 1',
      '    name: Migration',
      '    status: in-progress',
      '    slices:',
      '      - id: S001',
      '        name: migrate',
      '        status: done',
      '      - id: S002',
      '        name: verify',
      '        status: pending',
      '        when:',
      '          slice: S001',
      '          status: done',
      '',
    ].join('\n'),
  });
  try {
    const c = _ctx(root);
    assert.equal(handler.run([], c.ctx), 0);
    assert.match(c.out(), /S_M001_S001 -\. "if done" \.-> S_M001_S002/);
    assert.match(c.out(), /M_M001 --- S_M001_S001/);
  } finally { _cleanup(root); }
});

test('RGC-15: a condition on an undeclared slice is reported on stderr, not drawn', () => {
  const root = _project({
    tasks: [],
    roadmap: [
      'schema_version: 3',
      'milestones:',
      '  - id: M001',
      '    number: 1',
      '    name: Migration',
      '    slices:',
      '      - id: S001',
      '        name: migrate',
      '      - id: S002',
      '        name: verify',
      '        when:',
      '          slice: S099',
      '          status: done',
      '',
    ].join('\n'),
  });
  try {
    const c = _ctx(root);
    assert.equal(handler.run([], c.ctx), 0);
    assert.ok(!c.out().includes('S_M001_S099'), 'a phantom node must not be drawn:\n' + c.out());
    assert.match(c.err(), /dangling condition: M001\/S002 has a `when` on S099/);
  } finally { _cleanup(root); }
});
