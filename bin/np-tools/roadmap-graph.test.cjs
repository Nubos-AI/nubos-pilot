test('RGH-11: --out writes the file and reports instead of dumping the diagram', () => {
  const root = _project();
  const out = path.join(root, 'graph.md');
  try {
    const c = _ctx(root);
    assert.equal(handler.run(['--markdown', '--out', out], c.ctx), 0);
    assert.ok(fs.existsSync(out));
    assert.match(fs.readFileSync(out, 'utf-8'), /```mermaid/);
    const payload = JSON.parse(c.out());
    assert.equal(payload.ok, true);
    assert.equal(payload.out, out);
  } finally {
    _cleanup(root);
  }
});

