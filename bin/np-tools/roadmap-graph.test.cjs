test('RGH-6: --format dot emits a balanced digraph', () => {
  const root = _project();
  try {
    const c = _ctx(root);
    assert.equal(handler.run(['--format', 'dot'], c.ctx), 0);
    const text = c.out();
    assert.match(text, /digraph roadmap \{/);
    assert.equal((text.match(/\{/g) || []).length, (text.match(/\}/g) || []).length);
  } finally {
    _cleanup(root);
  }
});

test('RGH-7: an unknown format or level is refused', () => {
  const root = _project();
  try {
    const f = _ctx(root);
    assert.equal(handler.run(['--format', 'svg'], f.ctx), 1);
    assert.match(f.err(), /roadmap-graph-bad-format/);

    const l = _ctx(root);
    assert.equal(handler.run(['--level', 'epic'], l.ctx), 1);
    assert.match(l.err(), /roadmap-graph-bad-level/);
  } finally {
    _cleanup(root);
  }
});

test('RGH-8: --level milestone drops slices and tasks', () => {
  const root = _project();
  try {
    const c = _ctx(root);
    assert.equal(handler.run(['--level', 'milestone', '--json'], c.ctx), 0);
    const payload = JSON.parse(c.out());
    assert.equal(payload.stats.slices, 0);
    assert.equal(payload.stats.tasks, 0);
    assert.equal(payload.stats.milestones, 1);
  } finally {
    _cleanup(root);
  }
});

