'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const handler = require('./roadmap-graph.cjs');
const { _resetParseRoadmapCacheForTests } = require('../../lib/roadmap.cjs');

function _ctx(cwd) {
  const out = [];
  const err = [];
  return {
    ctx: { cwd, stdout: { write: (s) => out.push(s) }, stderr: { write: (s) => err.push(s) } },
    out: () => out.join(''),
    err: () => err.join(''),
  };
}

function _project(opts) {
  const o = opts || {};
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'np-rgh-'));
  const state = path.join(root, '.nubos-pilot');
  fs.mkdirSync(state, { recursive: true });
  fs.writeFileSync(path.join(state, 'roadmap.yaml'), o.roadmap || [
    'schema_version: 2',
    'milestones:',
    '  - id: M001',
    '    name: Password reset',
    '    status: in-progress',
    '    slices:',
    '      - id: S001',
    '        name: Token plumbing',
    '        status: done',
    '      - id: S002',
    '        name: Mail transport',
    '        status: pending',
    '',
  ].join('\n'), 'utf-8');
  for (const t of (o.tasks || [
    { s: 'S001', t: 'T0001', fm: 'status: done\ntitle: generate tokens' },
    { s: 'S001', t: 'T0002', fm: 'status: done\ntitle: consume tokens\ndepends_on: [T0001]' },
    { s: 'S002', t: 'T0003', fm: 'status: pending\ntitle: wire SMTP' },
  ])) {
    const dir = path.join(state, 'milestones', 'M001', 'slices', t.s, 'tasks', t.t);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, t.t + '-PLAN.md'), '---\n' + t.fm + '\n---\n\nBody.\n', 'utf-8');
  }
  _resetParseRoadmapCacheForTests();
  return root;
}

function _cleanup(root) {
  fs.rmSync(root, { recursive: true, force: true });
}

test('RGH-1: --help prints usage and exits zero', () => {
  const c = _ctx();
  assert.equal(handler.run(['--help'], c.ctx), 0);
  assert.match(c.out(), /roadmap-graph/);
  assert.match(c.out(), /Read-only/);
});

test('RGH-2: the default render is Mermaid at task level', () => {
  const root = _project();
  try {
    const c = _ctx(root);
    assert.equal(handler.run([], c.ctx), 0);
    assert.match(c.out(), /^%% Generated by/m);
    assert.match(c.out(), /flowchart TD/);
    assert.match(c.out(), /T_M001_S001_T0001/);
  } finally {
    _cleanup(root);
  }
});

test('RGH-3: node ids do not repeat the parent prefix', () => {
  // The first version composed ids blindly and produced
  // `T_M001_M001_S001_M001_S001_T0001` — unique, but unreadable in a diagram
  // whose entire purpose is being read.
  const root = _project();
  try {
    const c = _ctx(root);
    handler.run([], c.ctx);
    assert.ok(!/M001_M001/.test(c.out()), 'duplicated prefix in output:\n' + c.out());
  } finally {
    _cleanup(root);
  }
});

